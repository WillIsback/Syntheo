//! Export des liaisons TypeScript tauri-specta, partagé par les tests
//! `export_types` des plugins et de l'application (dépendance de dev).

use std::path::Path;

use tauri_specta::Builder;

/// Exporte les liaisons avec la configuration commune du dépôt.
pub fn export<R: tauri::Runtime>(builder: Builder<R>, path: impl AsRef<Path>) {
    builder
        .disable_serde_phases()
        .semantic_types(
            specta_typescript::semantic::Configuration::empty().enable_lossless_floats(),
        )
        .dangerously_cast_bigints_to_number()
        .export(specta_typescript::Typescript::default(), path)
        .unwrap();
}

/// Écrit le fichier de liaisons commité, précédé de `// @ts-nocheck`.
pub fn write_bindings<R: tauri::Runtime>(builder: Builder<R>, output_file: &str) {
    export(builder, output_file);

    let content = std::fs::read_to_string(output_file).unwrap();
    std::fs::write(output_file, format!("// @ts-nocheck\n{content}")).unwrap();
}

/// Vérifie que les commandes du manifeste du plugin sont exactement celles
/// des liaisons générées et des permissions autogénérées.
pub fn assert_command_manifest_is_single_source<R: tauri::Runtime>(
    builder: Builder<R>,
    plugin_name: &str,
    commands: &[&str],
) {
    let mut manifest_commands: Vec<String> =
        commands.iter().map(|command| command.to_string()).collect();
    manifest_commands.sort_unstable();

    // Export to a private path: export_types rewrites js/bindings.gen.ts
    // concurrently, so reading the shared file here would race with it.
    let bindings_path = std::env::temp_dir().join(format!(
        "syntheo-{plugin_name}-manifest-sync-{}.ts",
        std::process::id()
    ));
    export(builder, &bindings_path);
    let bindings = std::fs::read_to_string(&bindings_path).unwrap();
    let _ = std::fs::remove_file(&bindings_path);
    let prefix = format!("plugin:{plugin_name}|");
    let mut binding_commands: Vec<String> = bindings
        .split(prefix.as_str())
        .skip(1)
        .filter_map(|rest| rest.split('"').next().map(str::to_string))
        .collect();
    binding_commands.sort_unstable();
    binding_commands.dedup();
    assert_eq!(
        binding_commands, manifest_commands,
        "generated bindings drifted from src/manifest.rs"
    );

    let mut permission_commands: Vec<String> =
        std::fs::read_dir("./permissions/autogenerated/commands")
            .unwrap()
            .map(|entry| entry.unwrap().path())
            .filter(|path| path.extension().is_some_and(|ext| ext == "toml"))
            .filter_map(|path| {
                path.file_stem()
                    .map(|stem| stem.to_string_lossy().into_owned())
            })
            .collect();
    permission_commands.sort_unstable();
    assert_eq!(
        permission_commands, manifest_commands,
        "generated permissions drifted from src/manifest.rs"
    );
}
