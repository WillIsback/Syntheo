/// Raison de l'exclusion d'une commande de l'application, pour le journal.
pub(crate) fn exclusion_reason(cmd: &str) -> Option<&'static str> {
    EXCLUDED_COMMANDS
        .iter()
        .find(|(excluded, _)| *excluded == cmd)
        .map(|(_, reason)| *reason)
}

/// La commande passe-t-elle le relay, avec ces arguments ?
pub(crate) fn is_allowed(cmd: &str, args: &serde_json::Value) -> bool {
    if cmd == "plugin:opener2|open_url" {
        // Une adresse s'ouvre dans le programme par défaut ; `openWith`
        // choisirait le programme qui l'ouvre (contre-visite de l'issue 645).
        let with = args.get("openWith").or_else(|| args.get("open_with"));
        return with.is_none_or(serde_json::Value::is_null);
    }
    ALLOWED_COMMANDS.contains(&cmd)
        || ALLOWED_PREFIXES
            .iter()
            .any(|prefix| cmd.starts_with(prefix))
}
